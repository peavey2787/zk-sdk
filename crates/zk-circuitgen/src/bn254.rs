//! `circuits/lib/bn254/poseidon.circom`: Poseidon over the BN254 scalar field with the
//! circomlib-compatible x^5 parameters, taken from `light_poseidon` (the same constants the host
//! hashes with) rather than retyped. One template is emitted per supported input count.

use ark_bn254::Fr;
use light_poseidon::parameters::bn254_x5::get_poseidon_parameters;

use crate::emit::{function, grid, row};

/// Input counts with a `Poseidon<N>` template. Commitments hash 5 inputs.
const INPUTS: [usize; 1] = [5];

const PREAMBLE: &str = include_str!("bn254/poseidon_preamble.circom");
const TEMPLATE: &str = include_str!("bn254/poseidon_template.circom");

fn numbers(values: &[Fr]) -> Vec<String> {
    values.iter().map(|v| v.to_string()).collect()
}

fn emit_width(out: &mut String, inputs: usize) {
    let width = inputs + 1;
    let params = get_poseidon_parameters::<Fr>(width as u8).expect("supported Poseidon width");
    assert_eq!(params.alpha, 5, "the template's S-box is x^5");
    let arks = params.ark.len();
    assert_eq!(arks, width * (params.full_rounds + params.partial_rounds));
    function(
        out,
        &format!("poseidon_ark_{width}"),
        &format!("[{arks}]"),
        &row(&numbers(&params.ark)),
    );
    let mds: Vec<Vec<String>> = params.mds.iter().map(|r| numbers(r)).collect();
    function(
        out,
        &format!("poseidon_mds_{width}"),
        &format!("[{width}][{width}]"),
        &grid(&mds),
    );
    let sboxes = width * params.full_rounds + params.partial_rounds;
    out.push_str(
        &TEMPLATE
            .replace("{N}", &inputs.to_string())
            .replace("{T}", &width.to_string())
            .replace("{ARKS}", &arks.to_string())
            .replace("{RF}", &params.full_rounds.to_string())
            .replace("{RP}", &params.partial_rounds.to_string())
            .replace("{SBOXES}", &sboxes.to_string()),
    );
}

pub fn render() -> String {
    let mut out = String::from(
        "// GENERATED by crates/zk-circuitgen from light-poseidon's BN254 x^5 parameters.\n\
         // Do not edit; regenerate with `python scripts/build_circuits.py`.\n\
         pragma circom 2.2.0;\n\n",
    );
    out.push_str(PREAMBLE);
    for inputs in INPUTS {
        emit_width(&mut out, inputs);
    }
    out
}
