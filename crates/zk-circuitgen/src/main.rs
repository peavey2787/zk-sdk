//! Emits `circuits/lib/poseidon2.circom`: Plonky3's width-16 KoalaBear Poseidon2 constants and
//! linear layers, extracted from the pinned crate rather than retyped. The matrices are measured by
//! pushing unit vectors through Plonky3's own generic linear layers.
//!
//! usage: circuitgen <output.circom>

use std::fmt::Write;

use p3_field::{PrimeCharacteristicRing, PrimeField32};
use p3_koala_bear::{
    GenericPoseidon2LinearLayersKoalaBear, KoalaBear, KOALABEAR_POSEIDON2_RC_16_EXTERNAL_FINAL,
    KOALABEAR_POSEIDON2_RC_16_EXTERNAL_INITIAL, KOALABEAR_POSEIDON2_RC_16_INTERNAL,
};
use p3_poseidon2::GenericPoseidon2LinearLayers;

const WIDTH: usize = 16;
type Layer = fn(&mut [KoalaBear; WIDTH]);

fn number(value: KoalaBear) -> u32 {
    value.as_canonical_u32()
}

fn row(values: &[KoalaBear]) -> String {
    let items: Vec<String> = values.iter().map(|v| number(*v).to_string()).collect();
    format!("[{}]", items.join(", "))
}

/// Column `j` of the matrix is the image of the `j`-th unit vector.
fn matrix(layer: Layer) -> Vec<Vec<KoalaBear>> {
    let mut rows = vec![vec![KoalaBear::ZERO; WIDTH]; WIDTH];
    for column in 0..WIDTH {
        let mut state = [KoalaBear::ZERO; WIDTH];
        state[column] = KoalaBear::ONE;
        layer(&mut state);
        for (r, value) in state.iter().enumerate() {
            rows[r][column] = *value;
        }
    }
    rows
}

fn function(out: &mut String, name: &str, shape: &str, body: &str) {
    writeln!(
        out,
        "function {name}() {{\n    var v{shape} = {body};\n    return v;\n}}\n"
    )
    .unwrap();
}

fn grid(rows: &[Vec<KoalaBear>]) -> String {
    let lines: Vec<String> = rows.iter().map(|r| row(r)).collect();
    format!("[\n        {}\n    ]", lines.join(",\n        "))
}

fn rounds(rounds: &[[KoalaBear; WIDTH]]) -> String {
    grid(&rounds.iter().map(|r| r.to_vec()).collect::<Vec<_>>())
}

const TEMPLATE: &str = include_str!("poseidon2_template.circom");

fn render() -> String {
    let mut out = String::from(
        "// GENERATED by crates/zk-circuitgen from Plonky3's KoalaBear width-16 Poseidon2.\n\
         // Do not edit; regenerate with `python scripts/build_circuits.py`.\n\
         pragma circom 2.2.0;\n\n",
    );
    let external = matrix(GenericPoseidon2LinearLayersKoalaBear::external_linear_layer);
    let internal = matrix(GenericPoseidon2LinearLayersKoalaBear::internal_linear_layer);
    function(&mut out, "p2_external_matrix", "[16][16]", &grid(&external));
    function(&mut out, "p2_internal_matrix", "[16][16]", &grid(&internal));
    function(
        &mut out,
        "p2_rc_initial",
        "[4][16]",
        &rounds(&KOALABEAR_POSEIDON2_RC_16_EXTERNAL_INITIAL),
    );
    function(
        &mut out,
        "p2_rc_final",
        "[4][16]",
        &rounds(&KOALABEAR_POSEIDON2_RC_16_EXTERNAL_FINAL),
    );
    function(
        &mut out,
        "p2_rc_internal",
        "[20]",
        &row(&KOALABEAR_POSEIDON2_RC_16_INTERNAL),
    );
    out.push_str(TEMPLATE);
    out
}

fn main() {
    let path = std::env::args().nth(1).unwrap_or_else(|| {
        eprintln!("usage: circuitgen <output.circom>");
        std::process::exit(2);
    });
    if let Err(error) = std::fs::write(&path, render()) {
        eprintln!("error: {path}: {error}");
        std::process::exit(1);
    }
}
