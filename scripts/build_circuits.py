#!/usr/bin/env python3
"""Reproducible build of the built-in predicate circuits.

Everything is pinned and stays inside this repository (the compiler lives in the git-ignored
target/toolchain/circom): the KoalaBear-capable Circom fork is checked out at CIRCOM_REV and built
with cargo; the hash constants are regenerated by zk-circuitgen (Poseidon2 from the pinned Plonky3, BN254
Poseidon from light-poseidon); the
predicate mains are generated from one table; every circuit is compiled to testdata/predicates
(KoalaBear) and to testdata/groth16 (BN254, for Groth16);
and crates/zk-sdk/src/predicate/approved.rs and crates/zk-groth16/src/approved.rs record each
artifact's SHA-256, which is the approved circuit identity the SDK checks before it proves, verifies
or (for Groth16) derives a trusted setup's starting keys. No Groth16 key is part of the build.

usage: build_circuits.py          rebuild and rewrite the committed artifacts
       build_circuits.py --check  rebuild into target/ and fail if anything differs from the repo
"""
import hashlib
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CIRCOM_REPO = "https://github.com/Client-Side-Proving/circom"
CIRCOM_REV = "bb7ae6d406debbfe8afc68305cbd6106fda945bc"
TOOLCHAIN = ROOT / "target" / "toolchain" / "circom"
EXE = TOOLCHAIN / "target" / "release" / ("circom.exe" if sys.platform == "win32" else "circom")
WIDTHS = {32: 2, 64: 4, 128: 8}

OPERANDS = ", ".join(f"{n}_commitment, {n}_is_public, {n}_public" for n in "xyzt")
SUM_PUBLICS = "commitment, signed, plus, minus, plus_total, minus_total, accept_lt, accept_eq, accept_gt"

# name prefix -> (circom library, template, public inputs in declaration order, extra template arguments)
FAMILIES = {
    "open": ("library", "OpenCommitment", "commitment, signed", ""),
    "compare": ("library", "CompareToBound", "commitment, signed, accept_lt, accept_eq, accept_gt, bound", ""),
    "range": ("library", "InRange", "commitment, signed, lo_inclusive, hi_inclusive, lo, hi", ""),
    "compare_committed": ("library", "CompareCommitted", "left, right, signed, accept_lt, accept_eq, accept_gt", ""),
    "sum4": ("arithmetic", "WeightedSum", SUM_PUBLICS, ", 4"),
    "sum8": ("arithmetic", "WeightedSum", SUM_PUBLICS, ", 8"),
    "arith": ("arithmetic", "MulAdd", OPERANDS + ", signed, accept_lt, accept_eq, accept_gt, divide", ""),
    "anyrange": ("union", "InAnyRange", "commitment, signed, enabled, lo, hi", ""),
    "distance": ("proximity", "Distance", "x_commitment, y_commitment, signed, center_x, center_y, accept_lt, accept_eq, accept_gt, radius_sq", ""),
}
# Merkle set circuits exist for each supported depth (leaves = 2^depth); keep in step with
# `SET_DEPTHS` in crates/zk-sdk/src/predicate/set.rs.
SET_DEPTHS = (8, 20)
for _depth in SET_DEPTHS:
    FAMILIES[f"member{_depth}"] = ("sets", "SetMember", "commitment, signed, root", f", {_depth}")
    FAMILIES[f"absent{_depth}"] = ("sets", "SetAbsent", "commitment, signed, root", f", {_depth}")
    FAMILIES[f"cred{_depth}"] = ("credentials", "Credential", "a_commitment, s_commitment, e_commitment, signed, root, now", f", {_depth}")


def run(command, cwd=ROOT):
    if subprocess.run(command, cwd=cwd).returncode != 0:
        raise SystemExit(f"FAIL: {' '.join(map(str, command))}")


def ensure_compiler():
    if not TOOLCHAIN.exists():
        TOOLCHAIN.parent.mkdir(parents=True, exist_ok=True)
        run(["git", "clone", "--quiet", CIRCOM_REPO, str(TOOLCHAIN)])
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=TOOLCHAIN, capture_output=True, text=True).stdout.strip()
    if head != CIRCOM_REV:
        run(["git", "fetch", "--quiet", "origin"], TOOLCHAIN)
        run(["git", "checkout", "--quiet", CIRCOM_REV], TOOLCHAIN)
    if not EXE.exists() or head != CIRCOM_REV:
        run(["cargo", "build", "--release"], TOOLCHAIN)


def main_source(library, template, publics, arguments, limbs):
    return (
        "// GENERATED by scripts/build_circuits.py; edit the library or the table there.\n"
        f'pragma circom 2.2.0;\ninclude "{library}.circom";\n'
        f"component main {{ public [{publics}] }} = {template}({limbs}{arguments});\n"
    )


def circuits():
    """name -> (source path, source text or None when hand-written)."""
    table = {}
    for prefix, (library, template, publics, arguments) in FAMILIES.items():
        for bits, limbs in WIDTHS.items():
            name = f"{prefix}_{bits}"
            source = main_source(library, template, publics, arguments, limbs)
            table[name] = (f"circuits/predicates/{name}.circom", source)
    return table


def compile_circuit(source, out, field="koalabear"):
    """Compile with `circuits/lib/<field>` on the search path, which supplies the field's
    commit.circom (see circuits/lib/opens.circom)."""
    out.mkdir(parents=True, exist_ok=True)
    prime = {"koalabear": "koalabear", "bn254": "bn128"}[field]
    library = ROOT / "circuits" / "lib" / field
    run([str(EXE), str(ROOT / source), "--prime", prime, "-l", str(library), "--r1cs", "--sym", "-o", str(out)])


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def approved_rs(names, directory):
    lines = [
        "// GENERATED by scripts/build_circuits.py; do not edit.",
        "// Approved built-in circuits: the SHA-256 of each bundled R1CS is its trusted identity.",
        "",
        "use super::bundle::Bundled;",
        "",
        "pub(super) const BUNDLED: &[Bundled] = &[",
    ]
    for name in names:
        base = f"../../../../testdata/predicates/{name}"
        lines += [
            "    Bundled {",
            f'        name: "{name}",',
            f'        r1cs: include_bytes!("{base}.r1cs"),',
            f'        sym: include_str!("{base}.sym"),',
            f'        sha256: "{sha256(directory / (name + ".r1cs"))}",',
            "    },",
        ]
    return "\n".join(lines + ["];", ""])


def groth16_approved_rs(names, directory):
    lines = [
        "// GENERATED by scripts/build_circuits.py; do not edit.",
        "// Approved BN254 predicate circuits: the SHA-256 of each r1cs and sym is its identity. The files",
        "// are loaded at run time (see setup.rs) and refused unless they match; keys come from trusted",
        "// setups made by their users (see ceremony/).",
        "",
        "use crate::setup::Approved;",
        "",
        "pub(crate) const APPROVED: &[Approved] = &[",
    ]
    for name in names:
        lines += [
            "    Approved {",
            f'        name: "{name}",',
            f'        r1cs_sha256: "{sha256(directory / (name + ".r1cs"))}",',
            f'        sym_sha256: "{sha256(directory / (name + ".sym"))}",',
            "    },",
        ]
    return "\n".join(lines + ["];", ""])


def build(check):
    ensure_compiler()
    for field, library in (("koalabear", "poseidon2.circom"), ("bn254", "poseidon.circom")):
        run(["cargo", "run", "--quiet", "-p", "zk-circuitgen", "--", field, str(ROOT / "circuits" / "lib" / field / library)])
    table = circuits()
    for name, (source, text) in table.items():
        (ROOT / source).write_text(text, encoding="utf-8", newline="\n")
        compile_circuit(source, ROOT / "target" / "circuits")
    compile_circuit("circuits/kat/poseidon2_kat.circom", ROOT / "target" / "circuits")
    built = ROOT / "target" / "circuits"
    built_bn254 = ROOT / "target" / "circuits-bn254"
    # Every family is also compiled over BN254 for the Groth16 backend: the mains are the same files,
    # and `-l circuits/lib/bn254` swaps in the BN254 Poseidon commitment and Merkle hashes.
    groth16 = sorted(table)
    for name in groth16:
        compile_circuit(table[name][0], built_bn254, "bn254")
    names = sorted(table)
    generated = {
        ROOT / "crates" / "zk-sdk" / "src" / "predicate" / "approved.rs": approved_rs(names, built),
        ROOT / "crates" / "zk-groth16" / "src" / "approved.rs": groth16_approved_rs(groth16, built_bn254),
    }
    artifacts = [(built / f"{n}.{s}", ROOT / "testdata" / "predicates" / f"{n}.{s}") for n in names for s in ("r1cs", "sym")]
    artifacts += [(built / f"poseidon2_kat.{s}", ROOT / "testdata" / "kat" / f"poseidon2_kat.{s}") for s in ("r1cs", "sym")]
    artifacts += [(built_bn254 / f"{n}.{s}", ROOT / "testdata" / "groth16" / f"{n}.{s}") for n in groth16 for s in ("r1cs", "sym")]
    if check:
        stale = [str(dst) for src, dst in artifacts if not dst.exists() or dst.read_bytes() != src.read_bytes()]
        stale += [str(f) for f, text in generated.items() if not f.exists() or f.read_text(encoding="utf-8") != text]
        if stale:
            print("FAIL: committed circuit artifacts differ from a fresh build:\n  " + "\n  ".join(stale))
            return 1
        print(f"PASS: {len(names)} KoalaBear and {len(groth16)} BN254 predicate circuits reproduce byte for byte")
        return 0
    for directory in ("predicates", "groth16"):
        (ROOT / "testdata" / directory).mkdir(parents=True, exist_ok=True)
    for src, dst in artifacts:
        shutil.copyfile(src, dst)
    for file, text in generated.items():
        file.write_text(text, encoding="utf-8", newline="\n")
    print(f"PASS: built {len(names)} KoalaBear and {len(groth16)} BN254 predicate circuits (circom {CIRCOM_REV[:12]})")
    return 0


if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv[1:]))
